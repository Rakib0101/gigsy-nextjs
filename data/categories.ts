// Helper function to get all categories as a flat list
export const getAllCategories = () => {
  const categories: Array<{ name: string; slug: string; type: string }> = [];

  categoryData.byType.forEach((item) => {
    categories.push({ ...item, type: "type" });
  });

  categoryData.byOccasion.forEach((item) => {
    categories.push({ ...item, type: "occasion" });
  });

  categoryData.byColor.forEach((item) => {
    categories.push({ ...item, type: "color" });
  });

  categoryData.byShape.forEach((item) => {
    categories.push({ ...item, type: "shape" });
  });

  categoryData.byHoliday.forEach((item) => {
    categories.push({ ...item, type: "holiday" });
  });

  categoryData.byTheme.classic.forEach((item) => {
    categories.push({ ...item, type: "theme-classic" });
  });

  categoryData.byTheme.licensed.forEach((item) => {
    categories.push({ ...item, type: "theme-licensed" });
  });

  return categories;
};

// Helper function to get category by slug
export const getCategoryBySlug = (slug: string) => {
  const allCategories = getAllCategories();
  return allCategories.find((cat) => cat.slug === slug);
};

